#!/usr/bin/env node
// Reproducible: extract the ICONS map from docs/mocks/assets/js/waypoint.js into a
// typed TS registry consumed by w-ui's <w-icon>. The icon inner-SVG markup is
// a build-time constant from our own design system (never user input), so it is
// safe to render via bypassSecurityTrustHtml in the component (Risks #11 forbids
// bypass on USER content only).
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const FRONTEND = join(HERE, '..');
const REPO = join(FRONTEND, '..');
const SRC = join(REPO, 'docs', 'mocks', 'assets', 'js', 'waypoint.js');
const OUT = join(FRONTEND, 'projects', 'components', 'src', 'lib', 'icon', 'w-icons.ts');

const js = readFileSync(SRC, 'utf8');
const block = js.match(/var ICONS = \{([\s\S]*?)\n {2}\};/);
if (!block) {
  console.error('Could not locate ICONS map in waypoint.js');
  process.exit(1);
}

const icons = {};
// Each entry: "name": '<svg inner markup>' — attribute values use double quotes,
// so single-quoted JS string values never contain an unescaped single quote.
for (const m of block[1].matchAll(/"([\w-]+)":\s*'([^']*)'/g)) icons[m[1]] = m[2];

const names = Object.keys(icons);
if (names.length === 0) {
  console.error('No icons parsed.');
  process.exit(1);
}

const entries = names.map((n) => `  '${n}': '${icons[n]}',`).join('\n');
const out = `// GENERATED by frontend/scripts/gen-icons.mjs from docs/mocks/assets/js/waypoint.js.
// Do not edit by hand; re-run the script to regenerate. ${names.length} icons.
// Feather-style line icons, viewBox 0 0 24 24, stroked via the .w-icon CSS rule.

export const W_ICONS: Record<string, string> = {
${entries}
};

export type WIconName = keyof typeof W_ICONS;

export const W_ICON_NAMES = Object.keys(W_ICONS) as WIconName[];
`;

writeFileSync(OUT, out);
console.log(`Wrote ${names.length} icons to ${OUT}`);
